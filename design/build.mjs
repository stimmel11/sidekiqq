#!/usr/bin/env node
/**
 * SideKiqq design-token build. Zero dependencies (Node >= 18).
 *
 *   node design/build.mjs          regenerate every output
 *   node design/build.mjs --check  exit 1 if any committed output is stale (for CI)
 *
 * Source of truth: design/tokens.json. Outputs:
 *   design/dist/tokens.css               CSS variables, light + dark
 *   design/dist/tailwind-preset.cjs      Tailwind v3 preset that reads those variables
 *   design/dist/kotlin/SideKiqqTheme.kt  Jetpack Compose theme (phone + watch)
 *   brain/design/{tokens.css,tailwind-preset.cjs}  copies the brain builds from
 *     (Vercel builds with Root Directory = brain, so the brain must not import from ../design)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const t = JSON.parse(readFileSync(path.join(here, "tokens.json"), "utf8"));
const HEADER = "Generated by design/build.mjs from design/tokens.json. Do not edit by hand.";

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const px = (n) => (n === 0 ? "0" : `${n / 16}rem`);
const stack = (f) => `"${f.family}", ${f.fallback}`;
const IMPORTANCE = Object.keys(t.importance);

// ---------------------------------------------------------------- CSS
function modeVars(mode) {
  const lines = [];
  for (const [k, v] of Object.entries(t.color[mode])) lines.push(`--sk-${kebab(k)}: ${v};`);
  for (const level of IMPORTANCE) {
    const c = t.importanceColor[mode][t.importance[level].color];
    const name = level.toLowerCase();
    lines.push(`--sk-imp-${name}-fg: ${c.fg};`, `--sk-imp-${name}-bg: ${c.bg};`, `--sk-imp-${name}-rule: ${c.rule};`);
  }
  lines.push(`color-scheme: ${mode};`);
  return lines;
}

function css() {
  const shared = [];
  for (const [k, v] of Object.entries(t.brand)) shared.push(`--sk-brand-${k}: ${v};`);
  for (const role of ["heading", "body", "mono"]) shared.push(`--sk-font-${role}: ${stack(t.font[role])};`);
  for (const [k, v] of Object.entries(t.type)) {
    shared.push(`--sk-text-${k}-size: ${px(v.size)};`, `--sk-text-${k}-line: ${px(v.lineHeight)};`);
  }
  for (const [k, v] of Object.entries(t.space)) shared.push(`--sk-space-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.radius)) shared.push(`--sk-radius-${k}: ${v === 999 ? "999px" : px(v)};`);
  for (const [k, v] of Object.entries(t.motion)) shared.push(`--sk-motion-${k}: ${typeof v === "number" ? `${v}ms` : v};`);
  for (const [k, v] of Object.entries(t.layout)) shared.push(`--sk-layout-${kebab(k)}: ${px(v)};`);

  const block = (sel, lines, indent = "") => `${indent}${sel} {\n${lines.map((l) => `${indent}  ${l}`).join("\n")}\n${indent}}`;
  return [
    `/* ${HEADER} */`,
    `/* Fonts: ${t.font.googleFontsUrl} */`,
    "",
    block(":root", [...shared, ...modeVars("light")]),
    "",
    "/* Dark follows the OS unless the page pins data-theme=\"light\". */",
    "@media (prefers-color-scheme: dark) {",
    block(':root:not([data-theme="light"])', modeVars("dark"), "  "),
    "}",
    "",
    block(':root[data-theme="dark"]', modeVars("dark")),
    "",
    "@media (prefers-reduced-motion: reduce) {",
    "  :root {",
    "    --sk-motion-fast: 0ms;",
    "    --sk-motion-base: 0ms;",
    "    --sk-motion-slow: 0ms;",
    "  }",
    "}",
    "",
  ].join("\n");
}

// ---------------------------------------------------------------- Tailwind preset
function preset() {
  const colors = { brand: { ...t.brand } };
  for (const k of Object.keys(t.color.light)) colors[kebab(k)] = `var(--sk-${kebab(k)})`;
  colors.imp = {};
  for (const level of IMPORTANCE) {
    const n = level.toLowerCase();
    colors.imp[n] = { fg: `var(--sk-imp-${n}-fg)`, bg: `var(--sk-imp-${n}-bg)`, rule: `var(--sk-imp-${n}-rule)` };
  }
  const fontSize = {};
  for (const [k, v] of Object.entries(t.type)) {
    fontSize[k] = [px(v.size), { lineHeight: px(v.lineHeight), letterSpacing: `${v.tracking}em`, fontWeight: String(v.weight) }];
  }
  const spacing = {};
  for (const [k, v] of Object.entries(t.space)) spacing[k] = px(v);
  const borderRadius = {};
  for (const [k, v] of Object.entries(t.radius)) borderRadius[k] = v === 999 ? "999px" : px(v);
  const preset = {
    darkMode: ["variant", ['@media (prefers-color-scheme: dark) { &:not([data-theme="light"] *) }', '&:is([data-theme="dark"] *)']],
    theme: {
      extend: {
        colors,
        fontFamily: {
          heading: ["var(--sk-font-heading)"],
          body: ["var(--sk-font-body)"],
          mono: ["var(--sk-font-mono)"],
        },
        fontSize,
        spacing,
        borderRadius,
        transitionDuration: { fast: `${t.motion.fast}ms`, base: `${t.motion.base}ms`, slow: `${t.motion.slow}ms` },
        transitionTimingFunction: { sk: t.motion.easing },
        maxWidth: { content: px(t.layout.contentMax) },
        width: { nav: px(t.layout.navWidth) },
        minHeight: { touch: px(t.layout.touchTarget) },
        minWidth: { touch: px(t.layout.touchTarget) },
      },
    },
  };
  return `/* ${HEADER} */\n/** @type {import('tailwindcss').Config} */\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`;
}

// ---------------------------------------------------------------- Kotlin / Compose
function kotlin() {
  const argb = (hex) => {
    const m = /^#([0-9a-f]{6})$/i.exec(hex);
    if (m) return `Color(0xFF${m[1].toUpperCase()})`;
    const r = /rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/.exec(hex);
    if (!r) throw new Error(`Unsupported color ${hex}`);
    const a = Math.round(Number(r[4]) * 255);
    const h = (n) => Number(n).toString(16).padStart(2, "0").toUpperCase();
    return `Color(0x${h(a)}${h(r[1])}${h(r[2])}${h(r[3])})`;
  };
  const scheme = (mode) =>
    Object.entries(t.color[mode])
      .map(([k, v]) => `    ${k} = ${argb(v)},`)
      .join("\n");
  const imp = (mode) =>
    IMPORTANCE.map((level) => {
      const c = t.importanceColor[mode][t.importance[level].color];
      return `        Importance.${level} -> ImportanceColors(fg = ${argb(c.fg)}, bg = ${argb(c.bg)}, rule = ${argb(c.rule)})`;
    }).join("\n");
  const fields = Object.keys(t.color.light).map((k) => `    val ${k}: Color,`).join("\n");
  const brand = Object.entries(t.brand)
    .map(([k, v]) => `    val ${k[0].toUpperCase()}${k.slice(1)} = ${argb(v)}`)
    .join("\n");
  const typeStyle = (k, v) => {
    const fam = v.font === "heading" ? "HeadingFamily" : v.font === "mono" ? "MonoFamily" : "BodyFamily";
    return `    val ${k} = TextStyle(fontFamily = ${fam}, fontWeight = FontWeight(${v.weight}), fontSize = ${v.size}.sp, lineHeight = ${v.lineHeight}.sp, letterSpacing = ${v.tracking}.em)`;
  };
  const types = Object.entries(t.type).map(([k, v]) => typeStyle(k, v)).join("\n");
  const space = Object.entries(t.space).map(([k, v]) => `    val s${k} = ${v}.dp`).join("\n");
  const radius = Object.entries(t.radius).map(([k, v]) => `    val ${k} = ${v}.dp`).join("\n");

  return `// ${HEADER}
// Adoption: see design/README.md ("Compose theme"). Package is a suggestion; move the file into
// android/shared (or a new android/shared-ui module) and update the package line.
@file:Suppress("unused", "MagicNumber")

package com.sidekiqq.ui.theme

import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.runtime.CompositionLocalProvider
import androidx.compose.runtime.Immutable
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.em
import androidx.compose.ui.unit.sp

/** Raw brand values: ${t.name}, "${t.tagline}" (short: "${t.taglineShort}") */
object SkBrand {
    const val NAME = "${t.name}"
    const val TAGLINE = "${t.tagline}"
    const val TAGLINE_SHORT = "${t.taglineShort}"
${brand}
}

/** Mirrors the contract enum in com.sidekiqq.shared (ARCHITECTURE.md). */
enum class Importance { ${IMPORTANCE.join(", ")} }

@Immutable
data class ImportanceColors(val fg: Color, val bg: Color, val rule: Color)

@Immutable
data class SkColors(
${fields}
    val isDark: Boolean,
) {
    fun importance(level: Importance): ImportanceColors = if (isDark) darkImportance(level) else lightImportance(level)
}

val SkLightColors = SkColors(
${scheme("light")}
    isDark = false,
)

val SkDarkColors = SkColors(
${scheme("dark")}
    isDark = true,
)

private fun lightImportance(level: Importance) = when (level) {
${imp("light")}
}

private fun darkImportance(level: Importance) = when (level) {
${imp("dark")}
}

/**
 * Fonts: ${t.font.heading.family} (headings), ${t.font.body.family} (body), ${t.font.mono.family} (data).
 * Replace these with downloadable Google Fonts (androidx.compose.ui:ui-text-google-fonts) or bundled
 * res/font files. They default to the platform families so the theme compiles with no extra assets.
 */
var HeadingFamily: FontFamily = FontFamily.SansSerif
var BodyFamily: FontFamily = FontFamily.SansSerif
var MonoFamily: FontFamily = FontFamily.Monospace

object SkType {
${types}
}

object SkSpace {
${space}
}

object SkRadius {
${radius}
}

object SkMotion {
    const val FAST_MS = ${t.motion.fast}
    const val BASE_MS = ${t.motion.base}
    const val SLOW_MS = ${t.motion.slow}
}

val LocalSkColors = staticCompositionLocalOf { SkLightColors }

/** Wrap each app's root: \`SideKiqqTheme { AppContent() }\`. Read tokens with \`SideKiqqTheme.colors\`. */
@Composable
fun SideKiqqTheme(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {
    val c = if (darkTheme) SkDarkColors else SkLightColors
    val material = if (darkTheme) {
        darkColorScheme(
            primary = c.accent, onPrimary = c.accentText, background = c.bg, onBackground = c.text,
            surface = c.surface, onSurface = c.text, onSurfaceVariant = c.textMuted, outline = c.line,
            error = c.danger, onError = c.dangerText, tertiary = c.success, onTertiary = c.successText,
        )
    } else {
        lightColorScheme(
            primary = c.accent, onPrimary = c.accentText, background = c.bg, onBackground = c.text,
            surface = c.surface, onSurface = c.text, onSurfaceVariant = c.textMuted, outline = c.line,
            error = c.danger, onError = c.dangerText, tertiary = c.success, onTertiary = c.successText,
        )
    }
    CompositionLocalProvider(LocalSkColors provides c) {
        MaterialTheme(colorScheme = material, content = content)
    }
}

object SideKiqqTheme {
    val colors: SkColors
        @Composable get() = LocalSkColors.current
}
`;
}

// ---------------------------------------------------------------- write / check
const cssOut = css();
const presetOut = preset();
const outputs = [
  ["design/dist/tokens.css", cssOut],
  ["design/dist/tailwind-preset.cjs", presetOut],
  ["design/dist/kotlin/SideKiqqTheme.kt", kotlin()],
  ["brain/design/tokens.css", cssOut],
  ["brain/design/tailwind-preset.cjs", presetOut],
];

const check = process.argv.includes("--check");
let stale = 0;
for (const [rel, content] of outputs) {
  const file = path.join(root, rel);
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== content) {
      console.error(`stale: ${rel}`);
      stale++;
    }
    continue;
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log(`wrote ${rel}`);
}
if (check) {
  if (stale) {
    console.error(`${stale} output(s) out of date. Run: node design/build.mjs`);
    process.exit(1);
  }
  console.log("design outputs are up to date");
}
