#!/usr/bin/env node
// Generates apple/SideKiqq/Sources/Theme/SideKiqqTheme.swift from design/tokens.json.
// Zero dependencies (Node >= 18), like design/build.mjs.
//
//   node apple/scripts/gen-theme.mjs          # write the Swift theme
//   node apple/scripts/gen-theme.mjs --check  # exit 1 if the committed file is stale (CI)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const tokensPath = join(repo, "design", "tokens.json");
const outPath = join(repo, "apple", "SideKiqq", "Sources", "Theme", "SideKiqqTheme.swift");
const t = JSON.parse(readFileSync(tokensPath, "utf8"));

function rgba(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) {
    const n = parseInt(hex[1], 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255, 1];
  }
  const m = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/i.exec(value);
  if (m) return [Number(m[1]), Number(m[2]), Number(m[3]), Number(m[4])];
  throw new Error(`Unsupported color: ${value}`);
}

const f = (n) => (n / 255).toFixed(4);
const swiftColor = (v) => {
  const [r, g, b, a] = rgba(v);
  return `RGBA(${f(r)}, ${f(g)}, ${f(b)}, ${a})`;
};

const semanticKeys = Object.keys(t.color.light);
for (const k of semanticKeys) if (!(k in t.color.dark)) throw new Error(`dark theme missing ${k}`);

// Dynamic Type text style each step scales with.
const relativeTo = { display: ".largeTitle", h1: ".title", h2: ".title2", h3: ".headline", body: ".body", small: ".footnote", data: ".caption" };
// PostScript names of the bundled fonts (if the TTFs are not bundled, SwiftUI falls back to the system font).
const postscript = {
  heading: { 500: "SpaceGrotesk-Medium", 600: "SpaceGrotesk-SemiBold", 700: "SpaceGrotesk-Bold" },
  body: { 400: "Inter-Regular", 500: "Inter-Medium", 600: "Inter-SemiBold" },
  mono: { 400: "JetBrainsMono-Regular", 500: "JetBrainsMono-Medium" },
};
const systemWeight = { 400: ".regular", 500: ".medium", 600: ".semibold", 700: ".bold" };

const lines = [];
const out = (s = "") => lines.push(s);

out("// GENERATED by apple/scripts/gen-theme.mjs from design/tokens.json. Do not edit by hand.");
out(`// SideKiqq design tokens v${t.version}. Regenerate: node apple/scripts/gen-theme.mjs`);
out("import SwiftUI");
out("#if canImport(UIKit)");
out("import UIKit");
out("#endif");
out("");
out("private struct RGBA {");
out("    let r: Double, g: Double, b: Double, a: Double");
out("    init(_ r: Double, _ g: Double, _ b: Double, _ a: Double) { self.r = r; self.g = g; self.b = b; self.a = a }");
out("    var color: Color { Color(.sRGB, red: r, green: g, blue: b, opacity: a) }");
out("    #if canImport(UIKit)");
out("    var uiColor: UIColor { UIColor(red: r, green: g, blue: b, alpha: a) }");
out("    #endif");
out("}");
out("");
out("/** A color that follows the system light/dark appearance. */");
out("private func dynamic(_ light: RGBA, _ dark: RGBA) -> Color {");
out("    #if canImport(UIKit)");
out("    return Color(UIColor { $0.userInterfaceStyle == .dark ? dark.uiColor : light.uiColor })");
out("    #else");
out("    return light.color");
out("    #endif");
out("}");
out("");
out("enum SideKiqqTheme {");
out(`    static let tagline = ${JSON.stringify(t.tagline)}`);
out(`    static let taglineShort = ${JSON.stringify(t.taglineShort)}`);
out("");
out("    /** Brand colors (fixed, not theme-dependent). */");
out("    enum Brand {");
for (const [k, v] of Object.entries(t.brand)) out(`        static let ${k} = ${swiftColor(v)}.color`);
out("    }");
out("");
out("    /** Semantic colors; switch with light/dark mode. */");
out("    enum Palette {");
for (const k of semanticKeys) out(`        static let ${k} = dynamic(${swiftColor(t.color.light[k])}, ${swiftColor(t.color.dark[k])})`);
out("    }");
out("");
out("    /** Importance colors: fg is text on bg (passes AA); rule is the full-strength bar. Always pair with the written label. */");
out("    struct ImportanceStyle {");
out("        let fg: Color");
out("        let bg: Color");
out("        let rule: Color");
out("        let label: String");
out("    }");
out("");
for (const [group] of Object.entries(t.importanceColor.light)) {
  const L = t.importanceColor.light[group], D = t.importanceColor.dark[group];
  out(`    private static let ${group}Style = (fg: dynamic(${swiftColor(L.fg)}, ${swiftColor(D.fg)}), bg: dynamic(${swiftColor(L.bg)}, ${swiftColor(D.bg)}), rule: dynamic(${swiftColor(L.rule)}, ${swiftColor(D.rule)}))`);
}
out("");
out("    /** Keyed by the brain's importance wire value (CRITICAL, HIGH, MEDIUM, LOW, FYI). */");
out("    static func importance(_ wire: String) -> ImportanceStyle {");
out("        switch wire {");
for (const [level, def] of Object.entries(t.importance)) {
  out(`        case ${JSON.stringify(level)}: return ImportanceStyle(fg: ${def.color}Style.fg, bg: ${def.color}Style.bg, rule: ${def.color}Style.rule, label: ${JSON.stringify(def.label)})`);
}
out(`        default: return ImportanceStyle(fg: slateStyle.fg, bg: slateStyle.bg, rule: slateStyle.rule, label: wire.capitalized)`);
out("        }");
out("    }");
out("");
out("    /** Type scale (px from tokens) bound to a Dynamic Type text style so it scales with the user's setting. */");
out("    enum Typography {");
for (const [name, s] of Object.entries(t.type)) {
  const ps = postscript[s.font]?.[s.weight];
  if (!ps) throw new Error(`No font mapping for ${s.font} ${s.weight}`);
  out(`        static let ${name} = Font.custom(${JSON.stringify(ps)}, size: ${s.size}, relativeTo: ${relativeTo[name]})`);
}
out("        /** Line spacing to add on top of the font's natural line height (token lineHeight - size, approx.). */");
out("        enum LineSpacing {");
for (const [name, s] of Object.entries(t.type)) out(`            static let ${name}: CGFloat = ${Math.max(0, s.lineHeight - s.size * 1.2).toFixed(1)}`);
out("        }");
out("        /** System-font fallbacks with matching weights. */");
out("        enum System {");
for (const [name, s] of Object.entries(t.type)) {
  const design = s.font === "mono" ? ".monospaced" : ".default";
  out(`            static let ${name} = Font.system(${relativeTo[name]}, design: ${design}, weight: ${systemWeight[s.weight]})`);
}
out("        }");
out("    }");
out("");
out("    enum Space {");
for (const [k, v] of Object.entries(t.space)) out(`        static let s${k}: CGFloat = ${v}`);
out("    }");
out("");
out("    enum Radius {");
for (const [k, v] of Object.entries(t.radius)) out(`        static let ${k}: CGFloat = ${v}`);
out("    }");
out("");
out("    enum Motion {");
for (const [k, v] of Object.entries(t.motion)) if (typeof v === "number") out(`        static let ${k}: Double = ${(v / 1000).toFixed(3)}`);
out("    }");
out("");
out("    enum Layout {");
for (const [k, v] of Object.entries(t.layout)) out(`        static let ${k}: CGFloat = ${v}`);
out("    }");
out("}");
out("");

const generated = lines.join("\n");
if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : "";
  if (current !== generated) {
    console.error(`${relative(repo, outPath)} is stale. Run: node apple/scripts/gen-theme.mjs`);
    process.exit(1);
  }
  console.log("Swift theme is up to date.");
} else {
  writeFileSync(outPath, generated);
  console.log(`Wrote ${relative(repo, outPath)}`);
}
